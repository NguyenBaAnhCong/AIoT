import { Router } from 'express';
import { requireAuth, requirePermission } from '../../middleware/auth.js';
import { asyncHandler } from '../../utils/asyncHandler.js';
import * as c from './data-quality.controller.js';
const r = Router();
r.use(requireAuth);
r.get('/rules', requirePermission('data_quality.read'), asyncHandler(c.rules));
r.post('/rules', requirePermission('data_quality.write'), asyncHandler(c.createRule));
r.patch('/rules/:id', requirePermission('data_quality.write'), asyncHandler(c.updateRule));
r.post('/checks', requirePermission('data_quality.write'), asyncHandler(c.run));
r.get('/checks', requirePermission('data_quality.read'), asyncHandler(c.checks));
r.get('/stats', requirePermission('data_quality.read'), asyncHandler(c.stats));
r.get('/kpis', requirePermission('data_quality.read'), asyncHandler(c.kpis));
r.get('/issues', requirePermission('data_quality.read'), asyncHandler(c.issues));
r.post('/issues/:id/:action', requirePermission('data_quality.write'), asyncHandler(c.issueAction));
r.get('/audit', requirePermission('data_quality.read'), asyncHandler(c.audit));
export default r;
